#!/usr/bin/env python
"""
Extract BPS's Indeks Kemahalan Konstruksi (IKK) 2025 for every province and
kabupaten/kota, for pricing an RAB outside Jakarta.

Source: BPS, "Indeks Kemahalan Konstruksi Provinsi dan Kabupaten/Kota 2025"
(catalog 7102025, released 1 Oct 2025), bps.go.id. IKK compares the cost of
building the same thing in each region, reference Kota Surabaya = 100; BPS
builds it from Kemen PU's unit-price analyses (AHSP) and regional prices.

Dirory's priced book is DKI Jakarta (Jakarta's HSD), so a city's prices are
Jakarta's x IKK(city) / IKK(DKI Jakarta province).

Output: plugin/dirory_library/ui/ikk.js (the panel offers the cities) and
supabase/seed/ikk_2025.json.

Usage
  python scripts/extract-ikk.py path/to/ikk2025.pdf
"""

import json
import os
import re
import sys

import pymupdf

ROOT = os.path.join(os.path.dirname(__file__), "..")
CODE = re.compile(r"^\d{2}$|^\d{4}$")
VALUE = re.compile(r"^\d{2,3},\d{2}$")


def main(pdf: str) -> int:
    doc = pymupdf.open(pdf)
    provinces, cities = {}, []
    for page in doc:
        text = page.get_text()
        title = re.search(r"Tabel \d+\s+Indeks Kemahalan Konstruksi Menurut (Kabupaten/Kota di Provinsi (.+?)|Provinsi), 2025", text)
        if not title:
            continue
        province = title.group(2)
        lines = [l.strip() for l in text.split("\n") if l.strip()]
        i = 0
        while i < len(lines):
            if CODE.match(lines[i]):
                # code, name (one or more lines), value
                j = i + 1
                name = []
                while j < len(lines) and not VALUE.match(lines[j]) and not CODE.match(lines[j]):
                    name.append(lines[j])
                    j += 1
                if j < len(lines) and VALUE.match(lines[j]) and name:
                    code, label, ikk = lines[i], " ".join(name), float(lines[j].replace(",", "."))
                    if len(code) == 2:
                        provinces[code] = {"code": code, "name": label, "ikk": ikk}
                    elif province:
                        cities.append({"code": code, "name": label, "province": province, "ikk": ikk})
                    i = j + 1
                    continue
            i += 1
    # One row per code (tables repeat their header across pages, not rows).
    seen, unique = set(), []
    for c in cities:
        if c["code"] not in seen:
            seen.add(c["code"])
            unique.append(c)
    dki = provinces.get("31")
    print(f"{len(provinces)} provinces, {len(unique)} kabupaten/kota; DKI Jakarta IKK = {dki and dki['ikk']}")
    if not dki or len(unique) < 500:
        print("PROBLEM: expected DKI Jakarta and about 514 regions")
        return 1
    data = {
        "source": "BPS, Indeks Kemahalan Konstruksi Provinsi dan Kabupaten/Kota 2025 (katalog 7102025), Kota Surabaya = 100",
        "reference": {"name": "DKI Jakarta", "ikk": dki["ikk"]},
        "provinces": sorted(provinces.values(), key=lambda p: p["code"]),
        "cities": sorted(unique, key=lambda c: c["code"]),
    }
    with open(os.path.join(ROOT, "supabase", "seed", "ikk_2025.json"), "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)
    with open(os.path.join(ROOT, "plugin", "dirory_library", "ui", "ikk.js"), "w", encoding="utf-8") as fh:
        fh.write("/* Generated by scripts/extract-ikk.py from BPS IKK 2025. Do not edit. */\n")
        fh.write("(function (root) {\n  const IKK = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
        fh.write("  if (typeof module !== 'undefined' && module.exports) module.exports = IKK;\n  else root.DiroryIKK = IKK;\n")
        fh.write("})(typeof window !== 'undefined' ? window : this);\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
